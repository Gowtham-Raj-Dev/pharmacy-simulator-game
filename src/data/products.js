// ─── Generator ─────────────────────────────────────────────────────────────
function mulberry32(seed) {
  return function () {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const FORM_CATEGORY = {
  Tablet: 'Tablets', Capsule: 'Capsules', Syrup: 'Syrups', Suspension: 'Syrups', Solution: 'Syrups',
  Tonic: 'Tonics', Drops: 'Drops', Cream: 'Creams', Ointment: 'Ointments', Gel: 'Gels', Powder: 'Powders',
  Spray: 'Sprays', Lotion: 'Creams', Inhaler: 'Sprays', Lozenge: 'Tablets', Gum: 'Tablets',
};

const PACK_VARIANTS = ['', 'Value pack', 'Family pack', 'Clinic pack'];

export function buildCatalog(seed = 20261003) {
  const rnd = mulberry32(seed);
  const pick = (a) => a[Math.floor(rnd() * a.length)];
  const products = [];
  let n = 1;
  const today = new Date(2026, 9, 3);

  for (const base of BASES) {
    base.variants.forEach((variant, vi) => {
      const brands = brandsFor(base.key, vi);
      for (let bi = 0; bi < brands.length; bi++) {
        // Each brand × variant; some get an additional value-pack SKU to scale catalog.
        const single = (variant.section || base.section) === 'devices' || variant.form === 'Kit' || variant.form === 'Device';
        const skuCount = single ? 1 : 1 + (rnd() < 0.85 ? 1 : 0) + (rnd() < 0.5 ? 1 : 0) + (rnd() < 0.3 ? 1 : 0);
        for (let s = 0; s < skuCount; s++) {
          const brand = brands[bi].n;
          const status = variant.status || base.status;
          const section = variant.section || base.section;
          const category = variant.category || base.category || FORM_CATEGORY[variant.form] || 'First-aid products';
          const flags = [...new Set([...(base.flags || []), ...(variant.flags || [])])];
          if (variant.flags && variant.flags.length === 0 && base.flags.includes('contains_sugar') && (variant.tags || []).includes('sugar_free')) {
            const i = flags.indexOf('contains_sugar'); if (i >= 0) flags.splice(i, 1);
          }
          if ((variant.tags || []).includes('sugar_free')) { const i = flags.indexOf('contains_sugar'); if (i >= 0) flags.splice(i, 1); }
          const tags = [...new Set([...(base.tags || []), ...(variant.tags || [])])];
          const packLabel = PACK_VARIANTS[s];
          const mult = [1, 2.6, 4.8, 9][s];
          const price = Math.round((variant.price[0] + rnd() * (variant.price[1] - variant.price[0])) * mult / 1) ;
          const isGeneric = !!brands[bi].g;
          const finalPrice = Math.max(5, Math.round(isGeneric ? price * 0.7 : price));
          const r = rnd();
          const stock = r < 0.045 ? 0 : r < 0.12 ? 1 + Math.floor(rnd() * 4) : 6 + Math.floor(rnd() * 70);
          const monthsToExpiry = rnd() < 0.03 ? -1 - Math.floor(rnd() * 3) : 2 + Math.floor(rnd() * 34);
          const exp = new Date(today.getFullYear(), today.getMonth() + monthsToExpiry, 1);
          const id = 'P' + String(n).padStart(4, '0');
          const formWord = variant.form === 'Device' ? '' : variant.form;
          const name = `${brand}${isGeneric ? ' Generic' : ''} ${variant.strength}${formWord ? ' ' + formWord : ''}${packLabel ? ' · ' + packLabel : ''}`.replace(/\s+/g, ' ').trim();
          const packText = s === 0 ? variant.pack : `${variant.pack} ×${[1, 3, 6, 12][s]}`;
          products.push({
            id,
            sku: 'EDU-' + (100000 + n),
            name,
            brand: brand + (isGeneric ? ' Generic' : ''),
            baseKey: base.key,
            generic: base.generic,
            cls: base.cls,
            category,
            form: variant.form,
            strength: variant.strength,
            pack: packText,
            use: base.use,
            warnings: base.warnings,
            flags,
            tags,
            symptoms: base.symptoms,
            storage: base.storage,
            status,
            section,
            stock,
            maxStock: 80,
            price: finalPrice,
            manufacturer: brands[bi].m,
            expiry: `${String(exp.getMonth() + 1).padStart(2, '0')}/${exp.getFullYear()}`,
            expired: monthsToExpiry < 0,
            batch: 'B' + Math.floor(100000 + rnd() * 899999),
            isGeneric,
            note: variant.note || '',
            description: `Contains ${base.generic}${variant.strength && variant.form !== 'Device' ? ' (' + variant.strength + ')' : ''}. ${base.use} ${variant.note ? variant.note + ' ' : ''}Always read the label and follow advice from a qualified pharmacist or doctor.`,
            atlas: (n * 13 + bi * 5) % 64,
            // raw variant data (used to rebuild display text when the language changes)
            brandBase: brand, brandRank: bi, strengthRaw: variant.strength, packRaw: variant.pack, packIdx: s, packMult: [1, 3, 6, 12][s],
          });
          n++;
        }
      }
    });
  }
  return products;
}

